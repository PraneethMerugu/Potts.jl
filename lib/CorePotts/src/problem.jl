"""Saved states at integer MCS. `sol(t)` looks up a saved MCS exactly (no interpolation)."""
struct PottsSolution{S, P, A} <: SciMLBase.AbstractTimeseriesSolution{S, 1, Vector{S}}
    u::Vector{S}
    t::Vector{Int}
    prob::P
    alg::A
    retcode::SciMLBase.ReturnCode.T
    stats::PottsStats
end

function PottsSolution(integ::PottsIntegrator)
    S = isempty(integ.saved_u) ? Any : typeof(first(integ.saved_u))
    return PottsSolution(convert(Vector{S}, integ.saved_u), copy(integ.saved_t),
        integ.prob, integ.alg, integ.retcode, integ.stats)
end

function (sol::PottsSolution)(t::Integer)
    i = searchsortedfirst(sol.t, t)
    (i <= length(sol.t) && sol.t[i] == t) ||
        throw(ArgumentError("MCS $t was not saved; saved times are $(sol.t)"))
    return sol.u[i]
end
