"""
    frozen_kinds(sys)

The kinds whose cells' sites are frozen, as a tuple of `Int32`, or `nothing` (the default).
A system that returns kinds uses the standard rule: a site is frozen when its
owner's kind is listed or it lies outside the lattice domain. The rule builds the
problem's mask (`PottsProblem`, `remake`, checkpoint resume) and is recomputed on the
integrator's backend after lifecycle events. A problem with frozen kinds takes no other
`frozen` mask.
"""
frozen_kinds(sys) = nothing

"""
    frozen_varies(sys)

Whether the frozen mask follows the state during a run. Default: `frozen_kinds(sys) !==
nothing`. `false` means a static mask (none, a domain, a user `frozen`), never recomputed.
A system with a custom `remake_frozen` defines it: `true` to follow the state,
`false` for a deliberately static mask.
"""
frozen_varies(sys) = frozen_kinds(sys) !== nothing

"""
    remake_frozen(sys, prob, u0)

The frozen mask of a remade or reinitialized state `u0`: the standard rule when
`frozen_kinds(sys)` names kinds, else `prob.frozen` (a static mask).

A custom rule overrides this method **and must also define `frozen_varies(sys) = true`**;
without it the integrator treats the mask as static and never recomputes it, and `init`
warns. Defining `frozen_varies(sys) = false` (a deliberately static mask) silences the
warning.
A custom rule runs on a host copy of the state at every refresh; `frozen_reads(sys)`
limits that copy to the leaves the rule reads.
"""
remake_frozen(sys, prob, u0) = (k = frozen_kinds(sys)) === nothing ? prob.frozen : _standard_frozen(k, u0)

"""
    frozen_reads(sys)

The state leaves a custom `remake_frozen` rule reads at a refresh, as a tuple of `Symbol`s:
`:ownership` (the labels) or cell column names, each at most once. On a device, a refresh then
copies only these leaves to the host before running the rule; every other leaf is the live
device array: do not read it on the host (scalar indexing errors; `Array(...)` works but is
an uncounted transfer). `nothing` (the default) copies the whole state. A rule that reads model, site
or history quantities keeps the default. A name that is neither `:ownership` nor a cell column of
the state, or that is repeated, is an `ArgumentError` at `init` (and at every refresh), on every backend. The
standard rule (`frozen_kinds`) runs on the integrator's backend and ignores this hook.
"""
frozen_reads(sys) = nothing

# A custom `remake_frozen` without `frozen_varies(sys) = true` gives a static mask: say so.
function _check_frozen_hooks(@nospecialize(sys))         # (host, once per `init`)
    frozen_varies(sys) && return nothing
    which(remake_frozen, Tuple{typeof(sys), Any, Any}).module === CorePotts && return nothing
    # a `frozen_varies` defined outside CorePotts (even `false`, also on a supertype) is a choice (D-133)
    which(frozen_varies, Tuple{typeof(sys)}).module === CorePotts || return nothing
    @warn "`remake_frozen` is overridden for $(typeof(sys)) but `frozen_varies(sys)` is false: the " *
          "frozen mask stays static during a run. Define `CorePotts.frozen_varies(::$(typeof(sys))) = true`." maxlog = 1
    return nothing
end

# The declared reads of a custom rule (D-128): `nothing`, or a tuple of distinct `:ownership` and
# cell column names of `st`; checked at `init` and at every custom-rule refresh.
function _frozen_reads(@nospecialize(sys), @nospecialize(st))
    reads = frozen_reads(sys)
    reads === nothing && return nothing
    (reads isa Tuple && all(n -> n isa Symbol, reads)) || throw(ArgumentError(
            "`frozen_reads` must be `nothing` or a tuple of Symbols (`:ownership` or cell column names); got $(repr(reads))"
        )
    )
    for n in reads
        n === :ownership || haskey(st.cell, n) || throw(
            ArgumentError(
                "`frozen_reads` declares `$n`, which is neither `:ownership` nor a cell column of the state " *
            "(cell columns: $(join(keys(st.cell), ", ")))"))
    end
    allunique(reads) || throw(ArgumentError(
        "`frozen_reads` declares `$(reads[findfirst(n -> count(==(n), reads) > 1, reads)])` more than once; got $(repr(reads))"))
    return reads
end
_custom_frozen(@nospecialize(sys)) = frozen_varies(sys) && frozen_kinds(sys) === nothing

# the standard rule on a host state (without the domain, which `PottsProblem` adds)
function _standard_frozen(kinds, u)
    k = Array(u.cell.kind)
    return map(s -> s != 0 && _in_kinds(k[s], kinds), Array(u.ownership))
end
"""
    remake_function(sys, prob; kwargs...) -> (f, u0)

Hook for the symbolic layer: the `remake` keywords beyond the fixed ones (its
problem-construction keywords, such as Potts' solvers). Returns a new `f` built from them
and `prob.u0` re-laid out for it if its state layout depends on them (values kept);
everything else is kept. Here: every such keyword is an `ArgumentError`.
"""
function remake_function(sys, prob; kwargs...)
    throw(ArgumentError("remake: unknown keyword$(length(kwargs) == 1 ? "" : "s") " *
                        "$(join(("`$k`" for k in keys(kwargs)), ", "))"))
end

"""
    remake(prob::PottsProblem; f, u0, tspan, p, seed, replica, repeat, kwargs, …)

A new problem with the given parts changed and every other part kept. `p` is a parameter
object or a map (`[T => 5.0]`, also `[:T => 5.0]` for the fields of a `NamedTuple` parameter
object). A `solve` keyword (`saveat = 10`) joins the problem's `kwargs`; `kwargs = (; …)`
replaces them, but keeps the problem's `initializealg` unless they set one. `initializealg`
is kept with the problem: a new `u0` is initialized with the given one, or else with the
problem's. A new `initializealg` needs a new `u0` (nothing else is initialized again); without
one it is an `ArgumentError`. Other keywords are the symbolic layer's problem keywords (Potts: `field_solver`,
`solvers`, …).
"""
function SciMLBase.remake(
        prob::PottsProblem; f = prob.f, u0 = prob.u0, tspan = prob.tspan, p = prob.p, seed = prob.seed,
        replica = prob.replica, repeat = prob.repeat, kwargs = missing, rest...
    )
    kept(k) = k in SOLVE_KEYWORDS || k in (:abstol, :reltol, :initializealg)
    solvekw = NamedTuple(k => v for (k, v) in rest if kept(k))
    other = NamedTuple(k => v for (k, v) in rest if !kept(k))
    base = kwargs === missing ? prob.kwargs : NamedTuple(kwargs)
    given = merge(kwargs === missing ? (;) : base, solvekw)
    haskey(given, :initializealg) && _remake_initializealg(prob, f, u0, given.initializealg)
    (haskey(prob.kwargs, :initializealg) && !haskey(base, :initializealg)) &&
        (base = merge(base, (; initializealg = prob.kwargs.initializealg)))
    kw = merge(base, solvekw)
    # no algorithm is stored as the constructor stores it: not at all
    (haskey(kw, :initializealg) && kw.initializealg === nothing) && (kw = _without_init(kw))
    return _remake(prob, f, u0, tspan, p, seed, replica, repeat, other, kw)
end

# a new `initializealg` at `remake`: a value the model can apply, and a new `u0` for it to
# initialize (the problem's own is accepted as it is)
function _remake_initializealg(prob, f, u0, a)
    check_initializealg(f.sys, a)
    (u0 === prob.u0 && !isequal(a, get(prob.kwargs, :initializealg, nothing))) && throw(
        ArgumentError(
            "remake: `initializealg` initializes a new state; give it with `u0` " *
                "(`remake(prob; u0 = op, initializealg)`): without one, nothing would be initialized again"
        )
    )
    return nothing
end

# `remake`, compiled once for every model: specialized on the problem's type it was
# 0.7–1.3 s of compile for every model, although the remade problem has the same type
Base.@nospecializeinfer function _remake(
        @nospecialize(prob::PottsProblem), @nospecialize(f), @nospecialize(u0),
        @nospecialize(tspan), @nospecialize(p), seed, replica, repeat, @nospecialize(kwargs::NamedTuple),
        @nospecialize(solvekw::NamedTuple)
    )
    relaid = prob.u0
    if !isempty(kwargs)
        f === prob.f || throw(
            ArgumentError(
                "remake: give `f` or the keywords it is rebuilt from " *
                    "($(join(("`$k`" for k in keys(kwargs)), ", "))), not both"
            )
        )
        f, relaid = remake_function(f.sys, prob; kwargs...)
    end
    tangent = prob.tangent
    if p !== prob.p
        pgiven = p
        p = remake_parameters(f.sys, prob, pgiven)
        check_field_parameters(f, p)
        tangent = remake_tangent(f.sys, prob, pgiven, p)
    end
    frozen = prob.frozen
    if u0 !== prob.u0
        u0 = remake_state(f.sys, prob, u0, solvekw)
        frozen = remake_frozen(f.sys, prob, u0)
        tangent = without_initial(tangent)          # (the initial fields' derivative parts were the old state's)
    else
        u0 = relaid
    end
    return _problem(
        f, u0, prob.lattice, tspan, p, prob.contact, prob.proposal, prob.relations, prob.spacing, frozen,
        seed, replica, repeat, tangent, solvekw
    )
end

# A map given as the parameters of a problem without a model (`remake(prob; p = [:T => 5.0])`):
# the fields of its `NamedTuple` parameter object by name; any other map is an `ArgumentError`
function remake_parameters(::Nothing, prob, p::Union{AbstractDict, AbstractVector{<:Pair}, Tuple{Vararg{Pair}}})
    prob.p isa NamedTuple || throw(
        ArgumentError(
            "remake: a parameter map needs a model or a NamedTuple parameter object; this problem's is a " *
                "$(nameof(typeof(prob.p))): give the new parameter object itself"
        )
    )
    kvs = collect(p)
    ks = [_index_name(SymbolicIndexingInterface.parameter_index(prob, first(kv))) for kv in kvs]
    return SymbolicIndexingInterface.remake_buffer(prob, prob.p, ks, [last(kv) for kv in kvs])
end

Base.@kwdef mutable struct PottsStats
    mcs::Int = 0
    attempts::Int = 0
    accepted::Int = -1          # -1: not counted by this algorithm
    committed::Int = -1         # CheckerboardCPM only, else -1: copies committed
    launches::Int = 0
    refreshes::Int = 0          # frozen-mask recomputations (`refresh_frozen!`)
    # host↔device traffic (D-085; never counted on the CPU): explicit synchronizations,
    # host↔device array copies, and the bytes they moved
    syncs::Int = 0
    transfers::Int = 0
    transfer_bytes::Int = 0
    lifecycle::LifecycleStats = LifecycleStats()
    fields::FieldStats = FieldStats()       # the field solvers' counters (status words)
    ode_code::SciMLBase.ReturnCode.T = SciMLBase.ReturnCode.Default
    # Σ `f.track` over the committed copies (`CPMFunction(…; track)`, Potts `track = (:energy_change,)`):
    # `nothing` without a track. Exact after every step under `SequentialCPM`; under
    # `CheckerboardCPM` brought up to date at the host read points (D-140)
    accepted_energy_change::Union{Nothing, Float64} = nothing
    # copies the `Global` veto refused only for want of window (D-197): `nothing` for
    # a model without `Global`, else an `Int` (always 0 on SequentialCPM, with or without
    # `skip_interior`, and without a window); under `CheckerboardCPM` brought up to date at
    # the host read points
    connectivity_deferred::Union{Nothing, Int} = nothing
end

