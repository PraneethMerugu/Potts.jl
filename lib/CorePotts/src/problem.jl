# SciML interface: problem → init → step!/solve!, with CommonSolve dispatch so that
# `solve(prob, alg)`, `EnsembleProblem`, callbacks-by-integrator and `remake` behave as in
# the rest of SciML. Time is the integer MCS.

const STATUS_NONFINITE = UInt32(1)

"""
    PottsProblem(f::CPMFunction, u0::CPMState, lattice, tspan, p;
                 contact = Moore(1), proposal = VonNeumann(1), relations = (;), seed = 0,
                 replica = 0, repeat = 0, kwargs...)

A cellular Potts problem. `tspan = (t0, t1)` in MCS. `frozen` (a Bool mask) marks sites
that never change owner and never donate (walls, obstacles); an MCS is one attempt per
mobile site. `spacing` (per-axis lattice spacing,
default 1) is exposed as `ctx.spacing` to field primitives; give it in the model's float
type (Float32 for Metal). `contact` and the named `relations`
(e.g. `(; surface = Moore(1))`) are resolved on `lattice` and exposed to the model's
functions as `ctx.contact`, `ctx.surface`, …. `proposal` is the model's copy neighborhood,
used by algorithms constructed without one (`SequentialCPM()`). `p` is any isbits parameter object (a `NamedTuple`, or the `PottsParameters`
generated by the symbolic layer); changing it with `remake` or `setp(prob, x)(prob, v)` never
recompiles.

`tangent` (a `CorePotts.ParameterTangent`, or `nothing`) holds the parameters with derivative
parts of a run that differentiates its fields: `p` stays the primal object the CPM
reads, and the field groups also step the derivative parts along the run.

Any other keyword (`saveat`, `callback`, …) is a `solve` keyword kept in `prob.kwargs`: `solve`
and `init` merge them with their own, which take precedence (a `callback` of both runs both).
"""
mutable struct PottsProblem{F <: CPMFunction, S <: CPMState, L <: Lattice, R, Q, RS, H, FZ, P, TG, K} <:
    SciMLBase.AbstractSciMLProblem
    const f::F
    const u0::S
    const lattice::L
    const contact::R
    const proposal::Q                   # a neighbourhood spec, resolved at `init`
    const relations::RS
    const spacing::H
    const frozen::FZ
    const tspan::Tuple{Int, Int}
    p::P                                # the only mutable field: `setp(prob, x)(prob, v)` (same type)
    const seed::UInt64
    const replica::UInt32
    const repeat::UInt32
    const tangent::TG
    const kwargs::K                     # the problem's `solve` keywords (a NamedTuple)
end

PottsProblem(
    f::CPMFunction, u0::CPMState, lattice::Lattice, tspan, p; contact = Moore(1), proposal = VonNeumann(1),
    relations = (;), spacing = nothing, frozen = nothing, seed = 0, replica = 0, repeat = 0, tangent = nothing, kwargs...
) =
    _problem(
    f, u0, lattice, tspan, p, contact, proposal, relations, spacing, frozen, seed, replica, repeat, tangent,
    NamedTuple(kwargs)
)

# The checks and the resolved relations of a new problem, compiled once for every model:
# nothing here is specialized on the model's types (the problem type itself is built at the end)
Base.@nospecializeinfer function _problem(@nospecialize(f::CPMFunction), @nospecialize(u0::CPMState),
        @nospecialize(lattice::Lattice), @nospecialize(tspan), @nospecialize(p), @nospecialize(contact),
        @nospecialize(proposal), @nospecialize(relations), @nospecialize(spacing), @nospecialize(frozen), seed, replica,
        repeat, @nospecialize(tangent), @nospecialize(kwargs::NamedTuple)
    )
    size(u0.ownership) == lattice.dims ||
        throw(ArgumentError("state size $(size(u0.ownership)) ≠ lattice $(lattice.dims)"))
    t0, t1 = Int.(tspan)
    0 <= t0 <= t1 <= typemax(UInt32) ||
        throw(ArgumentError("tspan must satisfy 0 ≤ t0 ≤ t1 ≤ 2^32 - 1"))
    any(in((:contact, :proposal, :lattice, :mobility, :mcs, :spacing)), keys(relations)) &&
        throw(ArgumentError("relation names `contact`, `proposal`, `lattice`, `mobility`, `mcs`, `spacing` are reserved"))
    rs = map(r -> relation(r, lattice), NamedTuple(relations))
    h = spacing === nothing ? nothing : Tuple(spacing)
    h === nothing || (length(h) == ndims(lattice) && all(x -> x > 0, h)) ||
        throw(ArgumentError("spacing must be $(ndims(lattice)) positive numbers"))
    frozen === nothing || size(frozen) == lattice.dims ||
        throw(ArgumentError("frozen mask has size $(size(frozen)), lattice $(lattice.dims)"))
    kinds = frozen_kinds(f.sys)
    if kinds !== nothing                            # the standard rule decides the mask
        rule = _standard_frozen(kinds, u0)
        dom(m) = lattice.mask === nothing ? m : m .| .!lattice.mask
        frozen === nothing || dom(frozen) == dom(rule) || throw(ArgumentError(
            "a model with frozen kinds $kinds derives its frozen mask from the state; a " *
            "`frozen` mask that differs from it cannot be combined with them (give the " *
            "obstacle sites to a cell of a frozen kind instead)"))
        frozen = rule
    end
    if lattice.mask !== nothing                     # outside the domain: medium, never mobile
        all(i -> lattice.mask[i] || u0.ownership[i] == 0, eachindex(u0.ownership)) ||
            throw(ArgumentError("sites outside the lattice domain must belong to the medium (0)"))
        frozen = frozen === nothing ? .!lattice.mask : (frozen .| .!lattice.mask)
    end
    relation(proposal, lattice)                     # validate now; resolved again at `init`
    return PottsProblem(
        f, u0, lattice, relation(contact, lattice), proposal, rs, h, frozen, (t0, t1), p,
        UInt64(seed), UInt32(replica), UInt32(repeat), tangent, kwargs
    )
end

