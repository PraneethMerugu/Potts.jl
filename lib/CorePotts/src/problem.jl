# Ensembles: trajectory `i` is the template with `replica = template.replica + i` and
# `repeat = ctx.repeat - 1` (independent Philox streams, D-005; one compiled model), unless
# the user's `prob_func` already changed the seed or replica.

"""
    EnsembleProblem(prob::PottsProblem; prob_func, output_func, reduction, u_init, safetycopy = false)

A SciML ensemble of Potts runs. Trajectory `i` solves `remake(prob′; replica = prob.replica + i)`,
where `prob′ = prob_func(prob, ctx)` (default: `prob`), so trajectories are independent and
reproducible: trajectory `i` equals `solve(remake(prob; replica = prob.replica + i), alg)`.
"""
function SciMLBase.EnsembleProblem(prob::PottsProblem; prob_func = SciMLBase.DEFAULT_PROB_FUNC,
        safetycopy = false, kwargs...)
    pf = _ReplicaProbFunc(prob_func)
    return invoke(SciMLBase.EnsembleProblem, Tuple{Any}, prob; prob_func = pf, safetycopy, kwargs...)
end

"""
    solve(ens::EnsembleProblem, alg::CPMAlgorithm; backend = CPU(), trajectories, …)

An ensemble solved without an ensemble algorithm runs `EnsembleThreads()` on the CPU and
`EnsembleSerial()` on a device backend (one queue), with `backend` forwarded to every
trajectory's `solve`. Trajectories are the same whichever runs them (independent streams).
"""
function SciMLBase.__solve(prob::SciMLBase.AbstractEnsembleProblem, alg::CPMAlgorithm; backend = CPU(), kwargs...)
    ensemble = backend isa CPU ? EnsembleThreads() : EnsembleSerial()
    return SciMLBase.__solve(prob, alg, ensemble; backend, kwargs...)
end

struct _ReplicaProbFunc{F}
    f::F
end
function (r::_ReplicaProbFunc)(prob, ctx)
    q = r.f(prob, ctx)
    (q.seed == prob.seed && q.replica == prob.replica) || return q
    return remake(q; replica = prob.replica + UInt32(ctx.sim_id), repeat = UInt32(ctx.repeat - 1))
end

"""
    StateIndex(scope, name)

SymbolicIndexingInterface index of the named state array `getfield(st.scope, name)`
(`scope` ∈ `:cell`, `:site`, `:model`). Reading gives the array (a model variable: its
value); writing copies a same-sized array into the live storage, or fills it with a number.
"""
struct StateIndex
    scope::Symbol
    name::Symbol
end
_state_array(st::CPMState, i::StateIndex) = getfield(getfield(st, i.scope), i.name)
function Base.getindex(st::CPMState, i::StateIndex)
    a = _state_array(st, i)
    return i.scope === :model ? only(_to_host(nothing, a)) : a      # user read: not counted
end
Base.setindex!(st::CPMState, v, i::StateIndex) = _set_state_array!(nothing, st, v, i)
# `stats`: the integrator's `PottsStats` counting the host→device copy (D-085), or `nothing`
function _set_state_array!(stats, st::CPMState, v, i::StateIndex)
    a = _state_array(st, i)
    if v isa Number
        fill!(a, convert(eltype(a), v))      # a Float64 must not reach a Float32 device array
    else
        size(v) == size(a) ||
            throw(DimensionMismatch("$(i.scope) variable $(i.name) has size $(size(a)); got $(size(v))"))
        _copy!(stats, a, convert(Array{eltype(a)}, v))
    end
    return v
end

"""
Parameter object `p` with parameter `i` set to `v`, converted to the stored type (so the
parameter type, and the compiled code, never change). Symbolic layers add methods for their
parameter objects.
"""
function set_parameter(p::NamedTuple, v, i::Symbol)
    return merge(p, NamedTuple{(i,)}((convert(typeof(getfield(p, i)), v),)))
end

# Setters act on the live state and parameters of an integrator (`integ.u` is a host
# snapshot) and take effect from the next MCS. A problem's parameters are immutable (isbits):
# change them with `remake`.
function SymbolicIndexingInterface.set_state!(integ::PottsIntegrator, v, i::StateIndex)
    _sync!(integ.stats, integ.backend)
    _set_state_array!(integ.stats, integ.state, v, i)
    # the owner or kind decides which sites are frozen
    (i.scope === :cell && i.name === :kind) && refresh_frozen!(integ)
    return v
end
function SymbolicIndexingInterface.set_parameter!(integ::PottsIntegrator, v, i)
    integ.p = set_parameter(integ.f.sys, integ.p, v, i)
    return nothing
end

"""
    set_parameter(sys, p, v, i)

`set_parameter(p, v, i)` for the model described by `sys` (`CPMFunction.sys`): a symbolic
layer adds a method to validate the value and update parameters derived from `i`.
"""
set_parameter(sys, p, v, i) = set_parameter(p, v, i)

"""
    set_parameters(sys, p, vals, idxs)

Parameter object `p` with parameters `idxs` set to `vals` as one change (`setp(integ, [x,
y])`). By default one `set_parameter` per index; a symbolic layer adds a method so that
parameters derived from several of them are updated once, from all the new values.
"""
function set_parameters(sys, p, vals, idxs)
    for (v, i) in zip(vals, idxs)
        p = set_parameter(sys, p, v, i)
    end
    return p
end

# `setp(integ, [x, y])` (and `integ.ps[[x, y]] = v`) on an integrator: the parameters are set
# together, as one change (`set_parameters`), not one name at a time
struct ParameterSetter{I, O}
    idxs::I
    original::O
    run_hook::Bool
end
function (s::ParameterSetter)(integ::PottsIntegrator, vals)
    length(vals) == length(s.idxs) ||
        throw(DimensionMismatch("setp: $(length(s.idxs)) parameters, $(length(vals)) values"))
    integ.p = set_parameters(integ.f.sys, integ.p, vals, s.idxs)
    s.run_hook && SymbolicIndexingInterface.finalize_parameters_hook!(integ, s.original)
    return nothing
end
function (s::ParameterSetter)(valp, vals)
    for (v, i) in zip(vals, s.idxs)
        SymbolicIndexingInterface.set_parameter!(valp, v, i)
    end
    s.run_hook && SymbolicIndexingInterface.finalize_parameters_hook!(valp, s.original)
    return nothing
end
SymbolicIndexingInterface.setp(sys::Union{PottsIntegrator, PottsProblem, CPMFunction}, ps::Union{Tuple, AbstractVector};
                               run_hook = true) = parameter_setter(sys, ps, run_hook)

"""
    parameter_setter(sys, ps, run_hook)

`setp(sys, ps)` for several parameters `ps` of `sys` (an integrator, problem, function or
model description): a setter that applies them to an integrator as one change. A state in
the list (set those with `setu`, or both with `setsym`) or an unknown name is an
`ArgumentError` here, before anything is set.
"""
function parameter_setter(sys, ps, run_hook)
    isempty(ps) && return invoke(SymbolicIndexingInterface.setp, Tuple{Any, Any}, sys, ps; run_hook)
    for x in ps
        SymbolicIndexingInterface.is_parameter(sys, x) && continue
        SymbolicIndexingInterface.is_variable(sys, x) &&
            throw(ArgumentError("setp: `$x` is a state variable, not a parameter; set states with " *
                                "`setu`, or parameters and states together with `setsym`"))
        throw(_unknown_name(sys, x, "setp"))
    end
    return ParameterSetter(map(x -> SymbolicIndexingInterface.parameter_index(sys, x), ps), ps, run_hook)
end

function _unknown_name(sys, x, fn)
    SymbolicIndexingInterface.is_observed(sys, x) &&
        return ArgumentError("$fn: `$x` is read-only (a built-in or observed quantity) and cannot be set")
    return ArgumentError("$fn: `$x` is neither a parameter nor a state variable" * _names_hint(sys))
end
_names_hint(sys) = ""
_names_hint(x::Union{PottsIntegrator, PottsProblem, CPMFunction}) = _names_hint(SymbolicIndexingInterface.symbolic_container(x))

# `setsym(integ, [x, y, w])`: the parameters of the list are set as one change (as `setp`),
# then its states (as `setu`)
struct SymbolSetter{PS, SS}
    pset::PS
    sset::SS
    pk::Vector{Int}
    sk::Vector{Int}
end
function (s::SymbolSetter)(valp, vals)
    length(vals) == length(s.pk) + length(s.sk) ||
        throw(DimensionMismatch("setsym: $(length(s.pk) + length(s.sk)) names, $(length(vals)) values"))
    s.pset(valp, map(k -> vals[k], s.pk))
    s.sset(valp, map(k -> vals[k], s.sk))
    return nothing
end
SymbolicIndexingInterface.setsym(sys::Union{PottsIntegrator, PottsProblem, CPMFunction}, syms::Union{Tuple, AbstractVector}) =
    symbol_setter(sys, syms)

"""
    symbol_setter(sys, syms)

`setsym(sys, syms)` (and `setu`) for a list of names of `sys` (an integrator, problem,
function or model description). Its parameters are set as one change, as by `setp(sys,
parameters)` (a rejected value sets none of them); its states as by `setu`. A list of
states only is SymbolicIndexingInterface's setter; an unknown or read-only name is an
`ArgumentError` when the setter is built. A mixed list is all-or-nothing for its parameters
only: they are set first, so a rejected parameter value sets nothing, but a rejected state
value (set after them) leaves the new parameter values in place.
"""
function symbol_setter(sys, syms)
    generic() = invoke(SymbolicIndexingInterface.setsym, Tuple{Any, Any}, sys, syms)
    SymbolicIndexingInterface.symbolic_type(syms) isa SymbolicIndexingInterface.NotSymbolic || return generic()
    pk, sk = Int[], Int[]
    for (k, x) in enumerate(syms)
        if SymbolicIndexingInterface.symbolic_type(x) isa SymbolicIndexingInterface.NotSymbolic ||
           SymbolicIndexingInterface.is_variable(sys, x)
            push!(sk, k)                                  # a state (or a raw state index)
        elseif SymbolicIndexingInterface.is_parameter(sys, x)
            push!(pk, k)
        else
            throw(_unknown_name(sys, x, "setsym"))
        end
    end
    isempty(pk) && return generic()
    pset = parameter_setter(sys, [syms[k] for k in pk], true)
    isempty(sk) && return pset
    sset = invoke(SymbolicIndexingInterface.setsym, Tuple{Any, Any}, sys, [syms[k] for k in sk])
    return SymbolSetter(pset, sset, pk, sk)
end

function SymbolicIndexingInterface.set_parameter!(::PottsProblem, v, i)
    throw(ArgumentError("problem parameters are immutable; use `remake(prob; p = [$(repr(_index_name(i))) => $v])` " *
                        "(or `setp` on an integrator)"))
end

# A hand-written problem (`f.sys === nothing`): the fields of a NamedTuple parameter object
# are its parameters by name (`getp(integ, :T)`, `setp(integ, :T)`, `integ.ps[:T]`); any
# other parameter object has no names.
struct ParameterFields{P}
    p::P            # the parameter object; `nothing` for a function (no parameter object)
end
# index of field `name` of a NamedTuple parameter object
struct ParameterField
    name::Symbol
end
_index_name(i) = i
_index_name(i::ParameterField) = i.name
_parameter_container(::Nothing, x) = ParameterFields(SymbolicIndexingInterface.parameter_values(x))
_parameter_container(sys, x) = x.f

SymbolicIndexingInterface.symbolic_container(f::CPMFunction) = _function_container(f.sys)
_function_container(::Nothing) = ParameterFields(nothing)
_function_container(sys) = sys
SymbolicIndexingInterface.symbolic_container(integ::PottsIntegrator) = _parameter_container(integ.f.sys, integ)
SymbolicIndexingInterface.symbolic_container(prob::PottsProblem) = _parameter_container(prob.f.sys, prob)

_has_field(s::ParameterFields, x) = s.p isa NamedTuple && x isa Symbol && haskey(s.p, x)
_names_hint(s::ParameterFields) =
    s.p isa NamedTuple ? "; the parameters of a problem without a model are the fields of its NamedTuple " *
                         "parameter object: $(join(keys(s.p), ", "))" :
    s.p === nothing ? "; a function without a model has no parameter names (use its problem or integrator)" :
    "; a problem without a model has parameter names only if its parameter object is a NamedTuple " *
    "(this one is a $(nameof(typeof(s.p))))"
function _check_parameter_name(s::ParameterFields, x)
    SymbolicIndexingInterface.symbolic_type(x) isa SymbolicIndexingInterface.NotSymbolic && return nothing
    _has_field(s, x) || throw(ArgumentError("`$x` is not a parameter" * _names_hint(s)))
    return nothing
end
_check_parameter_name(s, x) = nothing

SymbolicIndexingInterface.is_parameter(s::ParameterFields, x) = _has_field(s, x)
function SymbolicIndexingInterface.parameter_index(s::ParameterFields, x)
    _check_parameter_name(s, x)
    return ParameterField(x)
end
SymbolicIndexingInterface.parameter_symbols(s::ParameterFields) = s.p isa NamedTuple ? collect(keys(s.p)) : Symbol[]
