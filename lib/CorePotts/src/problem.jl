# Ensembles: trajectory `i` is the template with `replica = template.replica + i` and
# `repeat = ctx.repeat - 1` (independent Philox streams, D-005; one compiled model), unless
# the user's `prob_func` already changed the seed or replica.

"""
    EnsembleProblem(prob::PottsProblem; prob_func, output_func, reduction, u_init, safetycopy = false)

A SciML ensemble of Potts runs. Trajectory `i` solves `remake(prob′; replica = prob.replica + i)`,
where `prob′ = prob_func(prob, ctx)` (default: `prob`), so trajectories are independent and
reproducible: trajectory `i` equals `solve(remake(prob; replica = prob.replica + i), alg)`.
"""
function SciMLBase.EnsembleProblem(prob::PottsProblem; prob_func = SciMLBase.DEFAULT_PROB_FUNC,
        safetycopy = false, kwargs...)
    pf = _ReplicaProbFunc(prob_func)
    return invoke(SciMLBase.EnsembleProblem, Tuple{Any}, prob; prob_func = pf, safetycopy, kwargs...)
end

"""
    solve(ens::EnsembleProblem, alg::CPMAlgorithm; backend = CPU(), trajectories, …)

An ensemble solved without an ensemble algorithm runs `EnsembleThreads()` on the CPU and
`EnsembleSerial()` on a device backend (one queue), with `backend` forwarded to every
trajectory's `solve`. Trajectories are the same whichever runs them (independent streams).
"""
function SciMLBase.__solve(prob::SciMLBase.AbstractEnsembleProblem, alg::CPMAlgorithm; backend = CPU(), kwargs...)
    ensemble = backend isa CPU ? EnsembleThreads() : EnsembleSerial()
    return SciMLBase.__solve(prob, alg, ensemble; backend, kwargs...)
end

struct _ReplicaProbFunc{F}
    f::F
end
function (r::_ReplicaProbFunc)(prob, ctx)
    q = r.f(prob, ctx)
    (q.seed == prob.seed && q.replica == prob.replica) || return q
    return remake(q; replica = prob.replica + UInt32(ctx.sim_id), repeat = UInt32(ctx.repeat - 1))
end

"""
    StateIndex(scope, name)

SymbolicIndexingInterface index of the named state array `getfield(st.scope, name)`
(`scope` ∈ `:cell`, `:site`, `:model`). Reading gives the array (a model variable: its
value); writing copies a same-sized array into the live storage, or fills it with a number.
"""
struct StateIndex
    scope::Symbol
    name::Symbol
end
_state_array(st::CPMState, i::StateIndex) = getfield(getfield(st, i.scope), i.name)
function Base.getindex(st::CPMState, i::StateIndex)
    a = _state_array(st, i)
    return i.scope === :model ? only(Array(a)) : a
end
function Base.setindex!(st::CPMState, v, i::StateIndex)
    a = _state_array(st, i)
    if v isa Number
        fill!(a, convert(eltype(a), v))      # a Float64 must not reach a Float32 device array
    else
        size(v) == size(a) ||
            throw(DimensionMismatch("$(i.scope) variable $(i.name) has size $(size(a)); got $(size(v))"))
        copyto!(a, convert(Array{eltype(a)}, v))
    end
    return v
end

"""
Parameter object `p` with parameter `i` set to `v`, converted to the stored type (so the
parameter type, and the compiled code, never change). Symbolic layers add methods for their
parameter objects.
"""
function set_parameter(p::NamedTuple, v, i::Symbol)
    return merge(p, NamedTuple{(i,)}((convert(typeof(getfield(p, i)), v),)))
end

# Setters act on the live state and parameters of an integrator (`integ.u` is a host
# snapshot) and take effect from the next MCS. A problem's parameters are immutable (isbits):
# change them with `remake`.
function SymbolicIndexingInterface.set_state!(integ::PottsIntegrator, v, i::StateIndex)
    KernelAbstractions.synchronize(integ.backend)
    integ.state[i] = v
    # the owner or kind decides which sites are frozen
    (i.scope === :cell && i.name === :kind) && refresh_frozen!(integ)
    return v
end
function SymbolicIndexingInterface.set_parameter!(integ::PottsIntegrator, v, i)
    integ.p = set_parameter(integ.f.sys, integ.p, v, i)
    return nothing
end

"""
    set_parameter(sys, p, v, i)

`set_parameter(p, v, i)` for the model described by `sys` (`CPMFunction.sys`): a symbolic
layer adds a method to validate the value and update parameters derived from `i`.
"""
set_parameter(sys, p, v, i) = set_parameter(p, v, i)
function SymbolicIndexingInterface.set_parameter!(::PottsProblem, v, i)
    throw(ArgumentError("problem parameters are immutable; use `remake(prob; p = [$(repr(i)) => $v])` " *
                        "(or `setp` on an integrator)"))
end

