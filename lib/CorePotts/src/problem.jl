"""
    PottsIntegrator

The integrator for a `PottsProblem`, a `SciMLBase.DEIntegrator`. `t` is the current MCS and
`integrator.u` the live state (on a device, its device arrays: read them with broadcasts or
`Array`, or take a host copy with [`current_state`](@ref)). A write into `integrator.u` is seen
from the next MCS; after one, call `derivative_discontinuity!(integrator, true)` so that the
frozen mask and the field groups follow it. `step!` enqueues one MCS without synchronizing;
`step!(integrator, n, true)` lands on MCS `t + n`. `integrator.sol` is the solution so far,
`integrator.opts` the run's `PottsOptions` and `integrator.iter` the MCS this run took.

`check_error(integrator)` is the cheap read of the run's health inside a callback: `Success`
while the run goes on, else the code that ended it. It reads a host field and does not
synchronize; a device failure is found at the next synchronization (a save, a host read, the
end of the run).
"""
mutable struct PottsIntegrator{Alg, Law, P, S, C, LCC, F, KF, Pa, Ctx, B, CB, MS, O <: PottsOptions} <: SciMLBase.DEIntegrator{Alg, true, S, Int}
    const prob::P
    const alg::Alg
    const law::Law
    const state::S
    const cache::C
    const lcache::LCC
    const f::F
    const kf::KF
    p::Pa
    const ctx::Ctx
    const backend::B
    const key::RNGKey
    t::Int
    tstop::Int                      # the end of the time span (`reinit!(integ; tf)` moves it)
    const opts::O
    const saved_t::Vector{Int}
    const saved_u::Vector{Any}
    retcode::SciMLBase.ReturnCode.T
    const stats::PottsStats
    const callbacks::CB             # tuple of DiscreteCallbacks, checked after every MCS
    nmobile::Int                    # mobile sites: the attempts of one MCS
    const mscratch::MS              # `MobileCounters` of the standard-rule refresh, or nothing
    iter::Int                       # the MCS this run took (`maxiters` counts them)
    finished::Bool                  # the end of the run was taken (`solve!`, or `done` of an iteration)
end

# Counts of the standard-rule refresh (D-081) run by `refresh_frozen!` and on the host
# lifecycle path: `device` = [unused, mobile-count change, changed sites], read into `host`
# at once. The device lifecycle (D-089) keeps its own counts on the device (`_fold_lifecycle!`).
struct MobileCounters{D, I}
    device::D
    host::Vector{I}             # I: `site_index_type` of the lattice (D-253)
end

# Ensemble statistics: totals over trajectories.
function Base.merge(a::PottsStats, b::PottsStats)
    l = LifecycleStats(; (f => getfield(a.lifecycle, f) + getfield(b.lifecycle, f) for f in fieldnames(LifecycleStats))...)
    fs = FieldStats(; solves = a.fields.solves + b.fields.solves, budget = a.fields.budget + b.fields.budget,
        floor = a.fields.floor + b.fields.floor, newton_budget = a.fields.newton_budget + b.fields.newton_budget,
        code = _rank(b.fields.code) > _rank(a.fields.code) ? b.fields.code : a.fields.code)
    return PottsStats(; mcs = a.mcs + b.mcs, attempts = a.attempts + b.attempts,
        accepted = (a.accepted < 0 || b.accepted < 0) ? -1 : a.accepted + b.accepted,
        committed = (a.committed < 0 || b.committed < 0) ? -1 : a.committed + b.committed,
        launches = a.launches + b.launches, refreshes = a.refreshes + b.refreshes,
        syncs = a.syncs + b.syncs, transfers = a.transfers + b.transfers,
        transfer_bytes = a.transfer_bytes + b.transfer_bytes, lifecycle = l, fields = fs,
        ode_code = b.ode_code != SciMLBase.ReturnCode.Default ? b.ode_code : a.ode_code,
        accepted_energy_change = (a.accepted_energy_change === nothing || b.accepted_energy_change === nothing) ? nothing : a.accepted_energy_change + b.accepted_energy_change,
        connectivity_deferred = (a.connectivity_deferred === nothing || b.connectivity_deferred === nothing) ? nothing :
                                a.connectivity_deferred + b.connectivity_deferred)
end

